# 1. Ввод массива с защитой от неверных символов
print("Введите элементы массива через пробел (только целые числа):")
while True:
    try:
        # Пытаемся превратить введенный текст в список чисел
        arr = list(map(int, input().split()))
        
        # Проверяем, не нажал ли пользователь Enter, ничего не введя
        if len(arr) == 0:
            print("Ошибка! Вы ничего не ввели. Попробуйте снова.")
            continue
            
        break  # Если ошибок нет, выходим из цикла ввода
        
    except ValueError:
        # Если возникла ошибка типа данных, выводим предупреждение
        print("Ошибка! Вводите только целые числа через пробел. Попробуйте снова.")

n = len(arr)
print(f"\nИсходный массив: {arr}\n")

# 2. Внешний цикл: начинаем со второго элемента (индекс 1)
# Первый элемент (индекс 0) считаем уже отсортированным
for i in range(1, n):
    # Сохраняем текущий элемент во временную переменную
    key = arr[i]
    
    # Индекс элемента, с которым будем сравнивать (идет перед key)
    j = i - 1
    
    print(f"Берем элемент {key}")
    
    # Сравниваем и сдвигаем элементы вправо
    # Пока не дошли до начала массива (j >= 0) 
    # И пока элемент в отсортированной части больше нашего key
    while j >= 0 and arr[j] > key:
        # Сдвигаем элемент вправо
        arr[j + 1] = arr[j]
        j -= 1 # Переходим к следующему элементу слева
        
    # Шаг 2.5: Вставляем текущий элемент на найденную позицию
    # (j + 1, потому что цикл while уменьшил j на единицу больше, чем нужно)
    arr[j + 1] = key
    
    # Выводим массив после вставки
    print(f"  Массив после шага {i}: {arr}")

print(f"\nОтсортированный массив: {arr}")