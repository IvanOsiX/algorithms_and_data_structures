# Защита от ввода чисел меньше или равных нулю
while True:
    n = int(input("Введите целое число N (N > 0): "))
    if n > 0:
        break
    print("Ошибка! N должно быть больше нуля. Попробуйте снова.\n")

# Переменная-накопитель для суммы
current_sum = 0

print(f"Вычисляем квадрат числа {n}:")
for i in range(1, n + 1):
    # Вычисляем текущее нечетное число: 2*i - 1
    odd_number = 2 * i - 1
    
    # Добавляем его к сумме
    current_sum += odd_number
    
    # Выводим текущее значение суммы, как просят в задании
    print(f"Добавили {odd_number}: текущая сумма = {current_sum}")

print(f"Итоговый квадрат числа: {current_sum}")