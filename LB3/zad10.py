# Защита от некорректного ввода
while True:
    a = int(input("Введите целое положительное число A: "))
    b = int(input("Введите целое положительное число B: "))
    
    if a > 0 and b > 0:
        break
    print("Ошибка! Числа должны быть больше нуля. Попробуйте снова.\n")

# Сохраняем исходные значения, чтобы потом вывести их в ответе
original_a = a
original_b = b

# Алгоритм Евклида
# Работаем до тех пор, пока второе число (остаток) не станет нулем
while b != 0:
    a, b = b, a % b     # a становится равным b, а b становится равным остатку от деления старого a на b

# Когда цикл завершится (b станет равно 0), в переменной 'a' будет лежать НОД
print(f"Наибольший общий делитель чисел {original_a} и {original_b} равен: {a}")