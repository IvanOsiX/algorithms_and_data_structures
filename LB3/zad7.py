# Защита от некорректного ввода
while True:
    a = float(input("Введите длину отрезка A: "))
    b = float(input("Введите длину отрезка B: "))
    
    if a > b > 0:
        break
    print("Ошибка! Нужно, чтобы A было больше B, и оба числа были положительными. Попробуйте снова.\n")

# Пока длина A позволяет отрезать кусок B, мы это делаем
while a >= b:
    a = a - b

# Когда цикл завершится, в переменной 'a' останется только остаток, в который не помещается отрезок B
print(f"Длина незанятой части: {round(a, 4)}")