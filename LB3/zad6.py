# Защита от некорректного ввода
while True:
    a = int(input("Введите целое число A (A > 0): "))
    b = int(input("Введите целое число B (B > A): "))
    
    if a > 0 and b > a:
        break
    print("Ошибка! A должно быть больше 0, а B должно быть больше A. Попробуйте снова.\n")

# Внешний цикл перебирает числа от A до B включительно
for i in range(a, b + 1):
    # Внутренний цикл повторяет печать числа i ровно i раз
    for j in range(i):
        print(i, end=" ")
    
    # Переходим на новую строку после того, как напечатали все повторения текущего числа
    print()