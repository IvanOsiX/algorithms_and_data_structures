# Защита от ввода N <= 0
while True:
    n = int(input("Введите целое число N (N > 0): "))
    if n > 0:
        break
    print("Ошибка! N должно быть больше нуля. Попробуйте снова.\n")

# Начальное значение для произведения
product = 1.0

# Перебираем от 1 до N включительно
for i in range(1, n + 1):
    # Вычисляем текущий множитель (1.1, 1.2 и т.д.)
    factor = 1.0 + i / 10
    
    # Умножаем текущее произведение на новый множитель
    product = product * factor

# Выводим результат, округляя до 4 знаков для красоты
print(f"Произведение {n} сомножителей: {product:.4f}")