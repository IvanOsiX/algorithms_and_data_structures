# Защита от некорректного ввода
while True:
    n = int(input("Введите целое число N (N > 1): "))
    if n > 1:
        break
    print("Ошибка! N должно быть больше 1. Попробуйте снова.\n")

k = 0
total_sum = 0

# Пока сумма меньше N, мы увеличиваем K и прибавляем его к сумме
while total_sum < n:
    k += 1             # Увеличиваем счетчик (1, 2, 3...)
    total_sum += k     # Добавляем текущее K к общей сумме

# Когда цикл завершится, total_sum станет >= n
print(f"Наименьшее число K: {k}")
print(f"Полученная сумма: {total_sum}")