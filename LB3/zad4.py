# Защита от ввода N <= 0
while True:
    n = int(input("Введите целое число N (N > 0): "))
    if n > 0:
        break
    print("Ошибка! N должно быть больше нуля. Попробуйте снова.\n")

a = float(input("Введите вещественное число A: "))

# Переменная для накопления суммы
total_sum = 0.0

# Переменная для текущего слагаемого.
# Начинаем с 1, так как первое слагаемое в формуле — это 1
current_term = 1.0

# Запускаем цикл N + 1 раз (от 0 до N включительно)
for i in range(n + 1):
    # Добавляем текущее слагаемое к сумме
    total_sum += current_term
    
    # Слагаемое для следующего шага
    current_term *= a

print(f"Сумма: {total_sum:.4f}")