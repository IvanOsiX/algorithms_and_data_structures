# Запрашиваем цену за 1 кг
price = float(input("Введите цену 1 кг конфет: "))

# Перебираем числа от 1 до 10 включительно
for i in range(1, 11):
    # Получаем вес: делим шаг цикла на 10 (1/10 = 0.1, 2/10 = 0.2 и т.д.)
    weight = i / 10
    
    # Считаем стоимость
    cost = weight * price
    
    # Выводим результат, округляя цену до 2 знаков после запятой
    print(f"{weight:.1f} кг конфет стоят: {cost:.2f}")