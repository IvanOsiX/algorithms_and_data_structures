# Защита от некорректного ввода (по условию 0 < P < 25)
while True:
    p = float(input("Введите процентную ставку P, больше 0, но меньше 25): "))
    if 0 < p < 25:
        break
    print("Ошибка! P должно быть больше 0 и меньше 25. Попробуйте снова.\n")

# Начальные значения
deposit = 1000.0  # Начальный вклад
months = 0        # Счетчик месяцев

# Пока вклад меньше или равен 1100, начисляем проценты
while deposit <= 1100:
    # Увеличиваем вклад на P процентов.
    deposit += (deposit * p / 100)
    
    # Увеличиваем счетчик месяцев
    months += 1

# Выводим результат
print(f"Количество месяцев: {months}")
print(f"Итоговый размер вклада: {deposit:.2f} руб.")