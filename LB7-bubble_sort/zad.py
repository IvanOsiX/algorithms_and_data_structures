# 1. Ввод массива с защитой от неверных символов
print("Введите элементы массива через пробел (только целые числа):")
while True:
    try:
        # Пытаемся превратить введенный текст в список чисел
        arr = list(map(int, input().split()))
        
        # Проверяем, не нажал ли пользователь Enter, ничего не введя
        if len(arr) == 0:
            print("Ошибка! Вы ничего не ввели. Попробуйте снова.")
            continue
            
        break  # Если ошибок нет, выходим из цикла ввода
        
    except ValueError:
        # Если возникла ошибка типа данных, выводим предупреждение
        print("Ошибка! Вводите только целые числа через пробел. Попробуйте снова.")

n = len(arr)
print(f"\nИсходный массив: {arr}\n")

# 2. Внешний цикл: количество проходов по массиву
for i in range(n - 1):
    # Флаг для оптимизации (о нем ниже)
    swapped = False 
    
    # 3. Внутренний цикл: сравнение соседних элементов
    # n - i - 1 нужно, чтобы не проверять элементы, которые уже "всплыли" в конец
    for j in range(n - i - 1):
        
        # 4. Если текущий элемент больше следующего — меняем их местами
        if arr[j] > arr[j + 1]:
            # Обмен значений делается в одну строчку
            arr[j], arr[j + 1] = arr[j + 1], arr[j]
            swapped = True
            
    # Выводим массив после каждого прохода
    print(f"Проход {i + 1}: {arr}")
    
    # Если за весь проход не было ни одной перестановки — массив отсортирован
    if not swapped:
        print("Массив уже отсортирован, досрочное завершение.")
        break

print(f"\nОтсортированный массив: {arr}")