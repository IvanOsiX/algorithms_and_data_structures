# Защита от некорректного ввода
while True:
    try:
        n = int(input("Введите целое число N (N > 0): "))
        if n > 0:
            break
        print("Ошибка! N должно быть больше нуля.\n")
    except ValueError:
        print("Ошибка! Введите целое число.\n")

# 1. Создаем пустой список (массив)
my_array = []

# 2. Заполняем его N первыми нечетными числами
for i in range(n):
    # Формула нечетного числа: 2 * i + 1
    # (если i=0, будет 1; если i=1, будет 3 и т.д.)
    odd_number = 2 * i + 1
    
    # Добавляем число в конец списка
    my_array.append(odd_number)

# 3. Выводим результат
print(f"Сформированный массив: {my_array}")