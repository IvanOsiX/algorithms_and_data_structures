# Защита от некорректного ввода N
while True:
    try:
        n = int(input("Введите целое число N (N > 2): "))
        if n > 2:
            break
        print("Ошибка! N должно быть больше 2.\n")
    except ValueError:
        print("Ошибка! Введите целое число.\n")

a = int(input("Введите первый элемент A: "))
b = int(input("Введите второй элемент B: "))

# 1. Создаем массив сразу с первыми двумя элементами
my_array = [a, b]

# 2. Заводим переменную для хранения суммы всех элементов
current_sum = a + b

# 3. Заполняем оставшуюся часть массива (с 3-го элемента до N-го)
# Индекс i начинается с 2
for i in range(2, n):
    # Добавляем накопленную сумму в массив
    my_array.append(current_sum)
    
    # Обновляем сумму: теперь она включает только что добавленный элемент
    current_sum += current_sum 
    # (это то же самое, что current_sum = current_sum + my_array[i])

# 4. Выводим результат
print(f"Сформированный массив: {my_array}")