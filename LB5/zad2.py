# Защита от некорректного ввода N
while True:
    try:
        n = int(input("Введите целое число N (N > 1): "))
        if n > 1:
            break
        print("Ошибка! N должно быть больше 1.\n")
    except ValueError:
        print("Ошибка! Введите целое число.\n")

# Вводим первый член и знаменатель (используем float, так как они могут быть дробными)
a = float(input("Введите первый член прогрессии A: "))
d = float(input("Введите знаменатель прогрессии D: "))

# 1. Создаем пустой массив (список)
progression = []

# 2. Текущий член прогрессии (начинаем с A)
current_term = a

# 3. Заполняем массив
for i in range(n):
    # Добавляем текущий член в массив
    progression.append(current_term)
    
    # Вычисляем следующий член для следующего шага цикла
    current_term *= d

# 4. Выводим результат
print(f"Сформированный массив: {progression}")