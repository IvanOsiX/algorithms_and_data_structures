# Ввод размеров и матрицы (с проверкой длины строк)
m = int(input("Введите количество строк M: "))
n = int(input("Введите количество столбцов N: "))

matrix = []
print(f"Введите элементы матрицы (по {n} чисел в каждой строке):")
for i in range(m):
    while True:
        row = list(map(int, input().split()))
        if len(row) == n:
            matrix.append(row)
            break
        print(f"Ошибка! Введите ровно {n} чисел.")

# Заводим флаг, чтобы понять, нашли мы столбец или нет
found = False

# Перебираем столбцы
for j in range(n):
    # Предполагаем, что текущий столбец состоит только из нечетных
    is_all_odd = True 
    
    # Проверяем каждый элемент в текущем столбце
    for i in range(m):
        # Если нашли хотя бы одно четное число
        if matrix[i][j] % 2 == 0:
            is_all_odd = False # Значит, столбец не подходит
            break              # Прерываем проверку этого столбца, переходим к следующему
            
    # Если после проверки всех строк is_all_odd осталось True
    if is_all_odd:
        print(f"Номер первого подходящего столбца: {j + 1}")
        found = True
        break # Нам нужен ПЕРВЫЙ столбец, поэтому выходим из внешнего цикла

# Если цикл закончился, а флаг found так и остался False
if not found:
    print("0")