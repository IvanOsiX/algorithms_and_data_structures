# 1. Ввод размеров и матрицы
m = int(input("Введите количество строк M: "))
n = int(input("Введите количество столбцов N: "))

matrix = []
print(f"Введите элементы матрицы (по {n} чисел в каждой строке):")
for i in range(m):
    while True:
        row = list(map(int, input().split()))
        if len(row) == n:
            matrix.append(row)
            break
        print(f"Ошибка! Введите ровно {n} чисел.")

# 2. Обработка каждого столбца
print("\nРезультаты по столбцам:")

# Внешний цикл перебирает столбцы (j)
for j in range(n):
    # Шаг А: Находим сумму элементов в текущем столбце
    col_sum = 0
    for i in range(m):
        col_sum += matrix[i][j]  # Обращаемся к элементу в строке i, столбце j
    
    # Вычисляем среднее арифметическое для этого столбца
    average = col_sum / m
    
    # Шаг Б: Считаем, сколько элементов больше среднего
    count_greater = 0
    for i in range(m):
        if matrix[i][j] > average:
            count_greater += 1
            
    # Выводим результат для текущего столбца
    # j + 1, потому что для людей столбцы начинаются с 1
    print(f"Столбец {j + 1}: среднее = {average:.2f}, элементов больше среднего = {count_greater}")