# 1. Ввод размеров и матрицы
m = int(input("Введите порядок квадратной матрицы M: "))

matrix = []
print(f"Введите элементы матрицы (по {m} чисел в каждой строке):")
for i in range(m):
    while True:
        row = list(map(int, input().split()))
        if len(row) == m:
            matrix.append(row)
            break
        print(f"Ошибка! Введите ровно {m} чисел.")

print("\nСуммы диагоналей (начиная с верхней правой):")

# 2. Диагонали, которые начинаются в ВЕРХНЕЙ строке (включая главную)
# Идем справа налево: от последнего столбца к нулевому
for start_col in range(m - 1, -1, -1):
    diag_sum = 0
    r, c = 0, start_col  # Начало диагонали (верхняя строка, столбец start_col)
    
    # Идем вниз-вправо, пока не упремся в границу
    while r < m and c < m:
        diag_sum += matrix[r][c]
        r += 1
        c += 1
        
    print(f"Диагональ, начинающаяся с элемента (0, {start_col}): сумма = {diag_sum}")

# 3. Диагонали, которые начинаются в ЛЕВОМ столбце (ниже главной)
# Идем сверху вниз: от 1-й строки до последней
for start_row in range(1, m):
    diag_sum = 0
    r, c = start_row, 0  # Начало диагонали (строка start_row, левый столбец)
    
    # Идем вниз-вправо
    while r < m and c < m:
        diag_sum += matrix[r][c]
        r += 1
        c += 1
        
    print(f"Диагональ, начинающаяся с элемента ({start_row}, 0): сумма = {diag_sum}")