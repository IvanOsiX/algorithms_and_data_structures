num = int(input("Введите целое число: "))

if num == 0:
    # Отдельно обрабатываем случай с нулем
    print("нулевое число")
else:
    # Если число не ноль, определяем его знак
    if num > 0:
        sign = "положительное"
    else:
        sign = "отрицательное"
        
    # Проверяем на четность с помощью остатка от деления
    if num % 2 == 0:
        parity = "четное"
    else:
        parity = "нечетное"
        
    # Выводим результат
    print(f"\n{sign} {parity} число")