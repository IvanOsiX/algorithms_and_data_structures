num = int(input("Введите число от 1 до 999: "))

# Проверяем, что число от 1 до 999
if num < 1 or num > 999:
    print("\nОшибка! Число должно быть от 1 до 999.")
else:
    # Определяем четность
    if num % 2 == 0:
        parity = "четное"
    else:
        parity = "нечетное"
        
    # Определяем разрядность (количество цифр)
    if num < 10:
        digits = "однозначное"
    elif num < 100:
        digits = "двузначное"
    else:
        digits = "трехзначное"
        
    # Выводим итоговую строку
    print(f"\n{parity} {digits} число")