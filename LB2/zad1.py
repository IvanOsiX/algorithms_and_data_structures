# Запрашиваем у пользователя целые числа
a = int(input("Введите число A: "))
b = int(input("Введите число B: "))

if a != b:
    # Если числа не равны, находим большее из них
    if a > b:
        b = a  # Если A больше, присваиваем B значение A
    else:
        a = b  # Иначе присваиваем A значение B
else:
    # Если числа равны, обнуляем оба
    a = 0
    b = 0

# Выводим результат
print(f"\nНовые значения: \nA = {a}\nB = {b}")