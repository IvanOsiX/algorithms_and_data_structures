while True:
    x = float(input("Введите координату x: "))
    y = float(input("Введите координату y: "))
    
    # Проверка, лежит ли точка на одной из осей
    if x == 0 or y == 0:
        print("\nТочка лежит на координатной оси. Введите другие значения.\n")
        continue
    # Если проверка пройдена, выходим из цикла
    break

# Проверяем знаки координат для каждой четверти
if x > 0 and y > 0:
    print("\nТочка находится в 1-й четверти")
elif x < 0 and y > 0:
    print("\nТочка находится во 2-й четверти")
elif x < 0 and y < 0:
    print("\nТочка находится в 3-й четверти")
else:
    print("\nТочка находится в 4-й четверти")