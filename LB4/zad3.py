def degree(x, n):
    # Базовый случай: любое число в степени 0 равно 1
    if n == 0:
        return 1
    # Рекурсивный шаг: умножаем x на результат степени на единицу меньше
    return x * degree(x, n - 1)

# Защита от некорректного ввода
while True:
    try:
        x = float(input("Введите число x: "))
        n = int(input("Введите целую степень n (n >= 0): "))
        if n >= 0:
            break
        print("Ошибка! Степень должна быть неотрицательным целым числом. Попробуйте снова.\n")
    except ValueError:
        print("Ошибка! Введите корректные числа.\n")

# Вызов функции и вывод результата
result = degree(x, n)
print(f"{x} в степени {n} равно: {result}")