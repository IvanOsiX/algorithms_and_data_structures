def hanoi(n, source, target, auxiliary):
    # Базовый случай: если остался один диск, переносим его и возвращаем 1 шаг
    if n == 1:
        print(f"Диск 1: {source} -> {target}")
        return 1
    
    # Рекурсивный шаг 1: переносим n-1 дисков на вспомогательный стержень.
    # Сохраняем количество шагов, которое на это потребовалось.
    steps_1 = hanoi(n - 1, source, auxiliary, target)
    
    # Переносим самый большой диск. Это 1 шаг.
    print(f"Диск {n}: {source} -> {target}")
    step_main = 1
    
    # Рекурсивный шаг 2: переносим n-1 дисков на целевой стержень.
    steps_2 = hanoi(n - 1, auxiliary, target, source)
    
    # Возвращаем общую сумму шагов для текущего вызова
    return steps_1 + step_main + steps_2

# Защита от некорректного ввода
while True:
    try:
        num = int(input("Введите количество дисков (N > 0): "))
        if num > 0:
            break
        print("Ошибка! Количество дисков должно быть больше нуля.\n")
    except ValueError:
        print("Ошибка! Введите целое число.\n")

print(f"Шаги для решения головоломки с {num} дисками:")
# Получаем результат работы функции (это и есть количество шагов)
total_steps = hanoi(num, 'A', 'C', 'B')

print(f"\nВсего сделано шагов: {total_steps}")