def is_prime(num):
    """Вспомогательная функция: проверяет, является ли число простым."""
    if num < 2:
        return False
    # Проверяем делители до квадратного корня из числа (для оптимизации)
    for i in range(2, int(num**0.5) + 1):
        if num % i == 0:
            return False
    return True

def decompose(n):
    # Рекурсивно раскладывает число на сумму простых чисел.
    # Базовый случай 1: если число меньше 2, разлагать нечего
    if n <= 1:
        return []
    
    # Базовый случай 2: если число само по себе простое, то это и есть ответ
    if is_prime(n):
        return [n]
    
    # Рекурсивный шаг: ищем наибольшее простое число, которое меньше n
    for p in range(n - 1, 1, -1):
        if is_prime(p):
            remainder = n - p
            # ВАЖНО: 1 не является простым числом. 
            # Поэтому если остаток равен 1, такое число 'p' нам не подходит.
            if remainder != 1:
                # Возвращаем найденное простое число и результат разложения остатка
                return [p] + decompose(remainder)

# --- Проверка работы ---
num = int(input("Введите целое число (больше 1): "))

if num > 1:
    result = decompose(num)
    # Красиво выводим результат, склеивая список через плюс
    print(f"{num} = " + " + ".join(map(str, result)))
else:
    print("Ошибка! Введите число больше 1.")