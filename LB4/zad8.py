def count_digits(n):
    # Берем модуль числа, чтобы отрицательные числа тоже работали (например, -123)
    n = abs(n)
    
    # Базовый случай: если число меньше 10, в нем одна цифра
    if n < 10:
        return 1
        
    # Рекурсивный шаг: 1 цифра + количество цифр в оставшемся числе
    return 1 + count_digits(n // 10)

# Защита от некорректного ввода
while True:
    try:
        num = int(input("Введите целое число: "))
        break
    except ValueError:
        print("Ошибка! Введите именно целое число.\n")

# Вызов функции и вывод результата
result = count_digits(num)
print(f"Количество цифр в числе {num}: {result}")