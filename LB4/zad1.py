def get_factorial(n):
    # Базовый случай: если n равно 0 или 1, возвращаем 1
    if n == 0 or n == 1:
        return 1
    # Рекурсивный шаг: умножаем n на факториал предыдущего числа
    else:
        return n * get_factorial(n - 1)

# Проверка на корректный ввод (факториал есть только у целых неотрицательных чисел)
while True:
    try:
        num = int(input("Введите целое неотрицательное число n: "))
        if num >= 0:
            break
        print("Ошибка! Число не может быть отрицательным. Попробуйте снова.\n")
    except ValueError:
        print("Ошибка! Введите именно целое число (без букв и точек).\n")

# Вызываем функцию и выводим результат
result = get_factorial(num)
print(f"Факториал числа {num} равен: {result}")