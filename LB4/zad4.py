def is_palindrome(s):
    # Убираем пробелы и приводим к нижнему регистру для надежности
    s = s.lower().replace(" ", "")
    
    # Базовый случай: строка из 0 или 1 символа — это палиндром
    if len(s) <= 1:
        return True
        
    # Если первый и последний символы не совпадают — это не палиндром
    if s[0] != s[-1]:
        return False
        
    # Рекурсивный шаг: отрезаем первый и последний символы и проверяем середину
    return is_palindrome(s[1:-1])

# Защита от пустого ввода
while True:
    text = input("Введите строку для проверки: ")
    if text:
        break
    print("Ошибка! Строка не должна быть пустой.\n")

# Вызов функции и вывод результата
if is_palindrome(text):
    print(f"Строка '{text}' является палиндромом.")
else:
    print(f"Строка '{text}' НЕ является палиндромом.")