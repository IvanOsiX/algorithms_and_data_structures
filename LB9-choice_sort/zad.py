# 1. Ввод массива с защитой от неверных символов
print("Введите элементы массива через пробел (только целые числа):")
while True:
    try:
        # Пытаемся превратить введенный текст в список чисел
        arr = list(map(int, input().split()))
        
        # Проверяем, не нажал ли пользователь Enter, ничего не введя
        if len(arr) == 0:
            print("Ошибка! Вы ничего не ввели. Попробуйте снова.")
            continue
            
        break  # Если ошибок нет, выходим из цикла ввода
        
    except ValueError:
        # Если возникла ошибка типа данных, выводим предупреждение
        print("Ошибка! Вводите только целые числа через пробел. Попробуйте снова.")

n = len(arr)
print(f"\nИсходный массив: {arr}\n")

# 2. Сортировка выбором (логика осталась прежней)
for i in range(n - 1):
    min_idx = i
    
    for j in range(i + 1, n):
        if arr[j] < arr[min_idx]:
            min_idx = j
            
    if min_idx != i:
        print(f"Шаг {i + 1}: Меняем {arr[i]} и {arr[min_idx]} (минимальный в остатке)")
        arr[i], arr[min_idx] = arr[min_idx], arr[i]
    else:
        print(f"Шаг {i + 1}: Элемент {arr[i]} уже на своем месте, ничего не меняем")
        
    print(f"   Массив: {arr}")

print(f"\nОтсортированный массив: {arr}")